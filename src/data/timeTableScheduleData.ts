/**
 * Replicates and adapts a complete day schedule with exact same period timings and table format
 */
export function buildIdenticalWorkingDaySchedule(
  targetDay: DayOfWeek,
  subjectPrefixes?: Record<string, string>
): TimeTableSlot[] {
  // Take Monday's slots as template format
  const mondaySlots = departmentMasterSchedule.filter((s) => s.dayOfWeek === 'Monday');

  return mondaySlots.map((mSlot) => {
    const dayCode = targetDay.toLowerCase().slice(0, 3);
    const id = `tt-${mSlot.course.toLowerCase().replace(/[^a-z0-9]/g, '')}-${dayCode}-p${mSlot.periodNumber}`;
    
    // Exact period timings guaranteed
    const timing = STANDARD_PERIOD_TIMINGS[mSlot.periodNumber || 1] || {
      startTime: mSlot.startTime,
      endTime: mSlot.endTime,
    };

    return {
      ...mSlot,
      id,
      dayOfWeek: targetDay,
      startTime: timing.startTime,
      endTime: timing.endTime,
      notes: mSlot.notes ? `${mSlot.notes} (${targetDay})` : undefined,
    };
  });
}

